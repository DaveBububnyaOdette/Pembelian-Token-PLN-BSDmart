-- Cek hasil (JOIN antar tabel)
SELECT s.no_trx, k.nama AS kasir, pl.nama AS pelanggan, p.jenis, s.total_bayar
FROM struk s
JOIN kasir k       ON s.id_kasir = k.id_kasir
JOIN pelanggan pl  ON s.id_pelanggan = pl.id_pelanggan
JOIN pembayaran p  ON s.id_pembayaran = p.id_pembayaran;
