-- Hapus tabel lama (termasuk tabel "transaksi" versi lama yang digabung)
DROP TABLE IF EXISTS transaksi CASCADE;
DROP TABLE IF EXISTS struk CASCADE;
DROP TABLE IF EXISTS pembayaran_tunai CASCADE;
DROP TABLE IF EXISTS pembayaran_qris CASCADE;
DROP TABLE IF EXISTS pembayaran CASCADE;
DROP TABLE IF EXISTS pln_prabayar CASCADE;
DROP TABLE IF EXISTS pelanggan CASCADE;
DROP TABLE IF EXISTS kasir CASCADE;

-- 1. KASIR  (class Kasir)
CREATE TABLE kasir (
    id_kasir VARCHAR(20) PRIMARY KEY,
    nama     VARCHAR(100) NOT NULL,
    username VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

-- 2. PELANGGAN  (class Pelanggan)
CREATE TABLE pelanggan (
    id_pelanggan VARCHAR(30) PRIMARY KEY,
    nama         VARCHAR(100) NOT NULL
);

-- 3. PLN_PRABAYAR  (class PLNPraBayar)  -> id_pln ditambahkan sbg primary key
CREATE TABLE pln_prabayar (
    id_pln        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_meter      VARCHAR(30)   NOT NULL,
    id_pel        VARCHAR(30)   NOT NULL,
    nama          VARCHAR(100)  NOT NULL,
    tarif_daya    VARCHAR(30),
    no_ref        VARCHAR(50),
    token         VARCHAR(30),
    jumlah_kwh    NUMERIC(12,2) NOT NULL,
    nominal_token NUMERIC(12,2) NOT NULL,
    biaya_admin   NUMERIC(12,2) NOT NULL
);

-- 4. PEMBAYARAN  (abstract class Pembayaran = parent, seperti tabel person)
--    kolom "jenis" = pembeda subclass (seperti kolom "role" di person)
CREATE TABLE pembayaran (
    id_pembayaran INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jenis         VARCHAR(10)   NOT NULL CHECK (jenis IN ('Tunai', 'QRIS')),
    jumlah        NUMERIC(12,2) NOT NULL,
    tanggal       VARCHAR(20)   NOT NULL,   -- String di class diagram
    waktu         VARCHAR(20)   NOT NULL    -- String di class diagram
);

-- 5. PEMBAYARAN_TUNAI  (class PembayaranTunai extends Pembayaran)
CREATE TABLE pembayaran_tunai (
    id_pembayaran INTEGER PRIMARY KEY
        REFERENCES pembayaran(id_pembayaran) ON DELETE CASCADE,
    uang_dibayar  NUMERIC(12,2) NOT NULL,
    kembalian     NUMERIC(12,2) NOT NULL
);

-- 6. PEMBAYARAN_QRIS  (class PembayaranQris extends Pembayaran)
CREATE TABLE pembayaran_qris (
    id_pembayaran   INTEGER PRIMARY KEY
        REFERENCES pembayaran(id_pembayaran) ON DELETE CASCADE,
    nomor_referensi VARCHAR(50) NOT NULL
);

-- 7. STRUK  (class Struk) -> penghubung semua class
--    Kasir 1..0* Struk | Pelanggan 1..0* Struk | Struk 1..1 PLNPraBayar | Struk 1..1 Pembayaran
CREATE TABLE struk (
    id_struk      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_trx        VARCHAR(30)  NOT NULL UNIQUE,
    nama_toko     VARCHAR(100) NOT NULL,
    alamat        VARCHAR(200) NOT NULL,
    tanggal       VARCHAR(20)  NOT NULL,
    waktu         VARCHAR(20)  NOT NULL,
    total_bayar   NUMERIC(12,2) NOT NULL,
    id_kasir      VARCHAR(20) NOT NULL REFERENCES kasir(id_kasir),
    id_pelanggan  VARCHAR(30) NOT NULL REFERENCES pelanggan(id_pelanggan),
    id_pln        INTEGER NOT NULL UNIQUE REFERENCES pln_prabayar(id_pln) ON DELETE CASCADE,
    id_pembayaran INTEGER NOT NULL UNIQUE REFERENCES pembayaran(id_pembayaran) ON DELETE CASCADE
);

